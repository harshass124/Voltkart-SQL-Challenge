/*
QUESTION 7: EMPLOYEE TEAM REVENUE

Objective:
Calculate the total completed-order revenue generated by each employee's entire team, including the employee and all direct and indirect reports.

Approach:
1. Used a recursive CTE to identify employee reporting relationships.
2. Assigned each employee as the root employee of their own team.
3. Recursively retrieved all employees reporting under each root employee at any depth.
4. Joined the employee hierarchy with fact_orders using sales_rep_id.
5. Filtered completed orders and calculated total team revenue using SUM(order_total).
6. Joined the aggregated revenue back to dim_employee to retrieve employee details.

SQL Concepts:
- Recursive CTE
- Self-Referencing JOIN
- UNION ALL
- Aggregation
- GROUP BY
- COALESCE()
*/


WITH Employee_Team AS
(
    -- Anchor member: Start with every employee
    SELECT
        employee_id AS root_employee_id,
        employee_id,
        employee_name,manager_id,
        role
    FROM dim_employee

    UNION ALL

    -- Recursive member: Find all employees reporting under them
    SELECT
        et.root_employee_id,
        e.employee_id,
        e.employee_name,
        e.role
    FROM dim_employee e
    INNER JOIN Employee_Team et
        ON e.manager_id = et.employee_id
),

Team_Revenue AS
(
    -- Calculate completed revenue for each employee's entire team
    SELECT
        et.root_employee_id,
        SUM(fo.order_total) AS team_total_revenue
    FROM Employee_Team et
    INNER JOIN fact_orders fo
        ON et.employee_id = fo.sales_rep_id
    WHERE fo.order_status = 'Completed'
    GROUP BY et.root_employee_id
)

-- Final output
SELECT
    e.employee_id,
    e.employee_name,
    e.role,
    COALESCE(tr.team_total_revenue, 0) AS team_total_revenue
FROM dim_employee e
LEFT JOIN Team_Revenue tr
    ON e.employee_id = tr.root_employee_id
ORDER BY e.employee_id
OPTION (MAXRECURSION 100);




